// No authenticated API proxy: the visitor must work when GitHub is inaccessible.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.STATUS_URL || 'http://127.0.0.1:3002/status-statut/';
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || undefined,args:['--no-sandbox']});
  const context = await browser.newContext({viewport:{width:1280,height:1000},serviceWorkers:'block'});
  const apiRequests = [], leaks = [], cdnRequests = [], errors = [];
  await context.addInitScript(() => localStorage.setItem('personal-access-token','test-token-must-not-leave-browser'));
  await context.route('https://api.github.com/**', route => {apiRequests.push(route.request().url());return route.fulfill({status:429,contentType:'application/json',body:JSON.stringify({message:'API rate limit exceeded'})});});
  await context.route('https://raw.githubusercontent.com/**', route => route.fulfill({status:429,body:'Too many requests'}));
  context.on('request', request => {
    if (request.headers().authorization || request.url().includes('test-token-must-not-leave-browser')) leaks.push(request.url());
    if (request.url().startsWith('https://cdn.jsdelivr.net/gh/')) cdnRequests.push(request.url());
  });
  const page = await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(new URL('?lang=en',base).href,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.documentElement.dataset.gcdsPublicData);
  await page.waitForFunction(()=>document.querySelectorAll('.live-status article').length>0);
  assert.ok(!page.url().includes('rate-limit-exceeded'));
  assert.ok(!(await page.locator('main').innerText()).includes('Personal Access Token'));
  assert.ok((await page.locator('.gcds-public-data-notice').innerText()).includes('updated'));
  assert.equal(await page.locator('.gcds-language-link').count(),1);
  if(process.env.SCREENSHOT_DIR) { fs.mkdirSync(process.env.SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.SCREENSHOT_DIR,'credential-free-desktop-en.png'),fullPage:true}); }
  await page.locator('.gcds-language-link').click();
  await page.waitForFunction(()=>document.querySelector('.gcds-public-data-notice')?.textContent.includes('mise'));
  const first = page.locator('.live-status h4 a').first();
  if(new URL(base).hostname==='127.0.0.1') await first.evaluate(link=>{const u=new URL(link.href);link.href=location.origin+u.pathname+u.search;});
  await first.click();
  await page.waitForFunction(()=>location.pathname.includes('/history/'));
  await page.locator('.gcds-history-back a').waitFor();
  await page.locator('main canvas').waitFor();
  assert.ok(!page.url().includes('rate-limit-exceeded'));
  await page.goto(new URL('incident/1?lang=en',base).href,{waitUntil:'networkidle'});
  await page.locator('main > footer a').waitFor();
  assert.ok(!(await page.locator('main').innerText()).includes('Personal Access Token'));
  await page.goto(new URL('rate-limit-exceeded?lang=en',base).href,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>!location.pathname.includes('rate-limit-exceeded'));
  await page.waitForFunction(()=>document.querySelectorAll('.live-status article').length>0);
  await page.setViewportSize({width:390,height:844});await page.locator('.gcds-language-link').click();
  if(process.env.SCREENSHOT_DIR) await page.screenshot({path:path.join(process.env.SCREENSHOT_DIR,'credential-free-mobile-fr.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(apiRequests,[],'No browser requests to GitHub API, even with a stored token');
  assert.deepEqual(leaks,[],'No Authorization headers or credentials on any network request');
  assert.ok(cdnRequests.some(url=>/@[a-f0-9]{40}\/manifest.json/.test(url)),'Snapshot is served by jsDelivr at an immutable commit');
  assert.ok(cdnRequests.some(url=>/@[a-f0-9]{40}\/graphs\//.test(url)),'Graph images use immutable jsDelivr URLs');
  assert.deepEqual(errors,[]);
  // Public-host failure must preserve labelled cached data, never invent a status.
  await context.route('**/public-status.json*', route=>route.abort());
  await context.route('https://cdn.jsdelivr.net/gh/**', route=>route.abort());
  await page.goto(new URL('?lang=en',base).href,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.documentElement.dataset.gcdsPublicData==='stale');
  assert.ok((await page.locator('.gcds-public-data-notice').innerText()).includes('Cached data'));
  assert.ok(await page.locator('.live-status article').count()>0);
  assert.deepEqual(apiRequests,[]);
  assert.deepEqual(leaks,[]);
  const empty = await browser.newContext({serviceWorkers:'block'});
  await empty.route('**/public-status.json*',route=>route.abort());
  await empty.route('https://cdn.jsdelivr.net/gh/**',route=>route.abort());
  await empty.route('https://api.github.com/**',route=>{apiRequests.push(route.request().url());return route.abort();});
  const unavailable = await empty.newPage();
  await unavailable.goto(base,{waitUntil:'networkidle'});
  await unavailable.waitForFunction(()=>location.pathname.replace(/\/$/,'').endsWith('/error'));
  assert.equal(await unavailable.locator('main input').count(),0);
  assert.ok(!(await unavailable.locator('main').innerText()).includes('Personal Access Token'));
  assert.deepEqual(apiRequests,[]);
  await empty.close();
  await browser.close();console.log('PASS: GitHub API/raw blocked, no token exposure, CDN graphs, home/history/incident, bilingual freshness, and old rate-limit recovery.');
})().catch(e=>{console.error(e);process.exit(1)});
